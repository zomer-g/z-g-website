async function seedFiles() {
  if (!FILES_DIR) throw new Error("Set TM_FILES_DIR to the folder holding the PDFs.");

  for (const doc of RULINGS) {
    const data = await readFile(path.join(FILES_DIR, doc.file));
    await prisma.uploadedFile.upsert({
      where: { filename: doc.file },
      update: { data, size: data.length, mimeType: "application/pdf" },
      create: { filename: doc.file, data, size: data.length, mimeType: "application/pdf" },
    });
  }
  console.log(`  files: ${RULINGS.length} upserted`);
}

async function tagCoverage() {
  const { count } = await prisma.mediaAppearance.updateMany({
    where: { id: { in: COVERAGE_IDS } },
    data: { caseTag: CASE_TAG },
  });
  console.log(`  coverage: ${count}/${COVERAGE_IDS.length} tagged`);
}

async function seedDocuments() {
  let created = 0;
  let updated = 0;

  for (const [index, doc] of RULINGS.entries()) {
    const url = fileUrl(doc.file);
    const existing = await prisma.caseDocument.findFirst({
      where: { caseTag: CASE_TAG, fileUrl: url },
    });

    const data = {
      caseTag: CASE_TAG,
      category: "ruling",
      title: doc.title,
      description: doc.description,
      docDate: doc.docDate,
      citation: doc.citation,
      authority: doc.authority,
      fileUrl: url,
      sourceUrl: null,
      order: index + 1,
      isActive: LIVE,
    };

    if (existing) {
      await prisma.caseDocument.update({ where: { id: existing.id }, data });
      updated++;
    } else {
      await prisma.caseDocument.create({ data });
      created++;
    }
  }

  console.log(`  documents: ${created} created, ${updated} updated`);
}

async function seedPost() {
  const author =
    (await prisma.user.findUnique({ where: { email: "zomerg@gmail.com" } })) ??
    (await prisma.user.findFirst({ where: { role: "ADMIN" } })) ??
    (await prisma.user.findFirst());

  if (!author) throw new Error("No user found to attribute the post to.");

  const tags = [
    "תולעת המשפט",
    "התמנון",
    "פומביות הדיון",
    "פרטיות",
    "צו איסור פרסום",
    "מידע ציבורי",
  ];

  const fields = {
    title: TITLE,
    content,
    excerpt: EXCERPT,
    status: POST_STATUS,
    seoTitle: TITLE,
    seoDesc: EXCERPT.slice(0, 300),
    tags,
    caseTag: CASE_TAG,
  } as const;

  const post = await prisma.plilistPost.upsert({
    where: { slug: SLUG },
    // publishedAt is stamped when the post actually goes live, not at draft time.
    update: { ...fields, ...(LIVE ? { publishedAt: new Date() } : {}) },
    create: { ...fields, slug: SLUG, authorId: author.id, publishedAt: new Date() },
  });

  console.log(`  post: /haplilist/${post.slug} (${post.status})`);
}

async function main() {
  const host = new URL(process.env.DATABASE_URL ?? "postgres://none").hostname;
  console.log(`Seeding case "${CASE_TAG}" on ${host} — ${LIVE ? "LIVE" : "hidden (pass --live to publish)"}`);
  await seedFiles();
  await tagCoverage();
  await seedDocuments();
  await seedPost();
  await prisma.$disconnect();
}

main().catch(async (e) => {
  console.error(e);
  await prisma.$disconnect();
  process.exit(1);
});
