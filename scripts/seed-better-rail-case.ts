async function seedCoverage() {
  let created = 0;
  let updated = 0;

  for (const [index, item] of COVERAGE.entries()) {
    const existing = await prisma.mediaAppearance.findFirst({
      where: { caseTag: CASE_TAG, url: item.url },
    });

    const data = {
      title: item.title,
      description: item.description,
      type: item.type ?? "article",
      source: item.source,
      date: item.date,
      url: item.url,
      order: index + 1,
      isActive: LIVE,
      caseTag: CASE_TAG,
    };

    if (existing) {
      await prisma.mediaAppearance.update({ where: { id: existing.id }, data });
      updated++;
    } else {
      await prisma.mediaAppearance.create({ data });
      created++;
    }
  }

  console.log(`  coverage: ${created} created, ${updated} updated`);
}

async function seedDocuments() {
  let created = 0;
  let updated = 0;

  const all = [...LETTERS, ...RULINGS];

  for (const [index, doc] of all.entries()) {
    const existing = await prisma.caseDocument.findFirst({
      where: { caseTag: CASE_TAG, fileUrl: doc.fileUrl },
    });

    const data = {
      caseTag: CASE_TAG,
      category: doc.category,
      title: doc.title,
      description: doc.description,
      docDate: doc.docDate ?? null,
      citation: doc.citation ?? null,
      authority: doc.authority ?? null,
      fileUrl: doc.fileUrl,
      order: index + 1,
      isActive: LIVE,
    };

    if (existing) {
      await prisma.caseDocument.update({ where: { id: existing.id }, data });
      updated++;
    } else {
      await prisma.caseDocument.create({ data });
      created++;
    }
  }

  console.log(`  documents: ${created} created, ${updated} updated`);
}

async function seedPost() {
  const author =
    (await prisma.user.findUnique({ where: { email: "zomerg@gmail.com" } })) ??
    (await prisma.user.findFirst({ where: { role: "ADMIN" } })) ??
    (await prisma.user.findFirst());

  if (!author) throw new Error("No user found to attribute the post to.");

  const tags = [
    "רכבת ישראל",
    "Better Rail",
    "מידע ציבורי",
    "קניין רוחני",
    "חופש מידע",
    "תחבורה ציבורית",
  ];

  const post = await prisma.plilistPost.upsert({
    where: { slug: SLUG },
    update: {
      title: TITLE,
      content,
      excerpt: EXCERPT,
      status: POST_STATUS,
      seoTitle: TITLE,
      seoDesc: EXCERPT.slice(0, 300),
      tags,
      caseTag: CASE_TAG,
    },
    create: {
      slug: SLUG,
      title: TITLE,
      content,
      excerpt: EXCERPT,
      status: POST_STATUS,
      publishedAt: new Date(),
      authorId: author.id,
      seoTitle: TITLE,
      seoDesc: EXCERPT.slice(0, 300),
      tags,
      caseTag: CASE_TAG,
    },
  });

  console.log(`  post: /haplilist/${post.slug} (${post.status})`);
}

